//! Line-level three-way merges of text files both sides changed, with `git merge-file`.
//!
//! The inputs are the workspace's version (ours), the fork-time version (the ancestor), and
//! the project's version (theirs). A clean merge keeps both sides' edits; overlapping hunks
//! get standard conflict markers labelled `workspace`, `fork`, and `project`. Binary files,
//! very large files, and hosts without `git` are left to whole-file conflict handling.

use std::fs;
use std::os::unix::fs::{MetadataExt, PermissionsExt};
use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};
use std::sync::OnceLock;

use crate::changes::is_binary;
use crate::error::Result;
use crate::sync::ancestor;
use crate::sync::install::detect_package_manager;
use crate::sync::journal::{Fingerprint, MergedStep};
use crate::util::IoContext;
use crate::workspace::Workspace;

/// Files larger than this are never merged line by line.
const MAX_MERGE_BYTES: u64 = 8 << 20;

/// The first line of a conflict hunk, as written by [`merge_text`].
pub const OURS_MARKER: &str = "<<<<<<< workspace";
/// The last line of a conflict hunk, as written by [`merge_text`].
pub const THEIRS_MARKER: &str = ">>>>>>> project";

/// How overlapping hunks are resolved.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Favor {
    /// Keep both sides between conflict markers.
    Neither,
    /// Take the workspace's lines (`merge --overwrite-base`).
    Workspace,
    /// Take the project's lines (`pull --theirs`).
    Project,
}

/// The result of a line-level merge.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Merged {
    /// Both sides' edits combined without overlap.
    Clean(Vec<u8>),
    /// The merged text with this many hunks between conflict markers.
    Conflicted(Vec<u8>, usize),
}

/// Merge `ours` and `theirs` line by line against `ancestor`. `None` means the files cannot
/// be merged as text (binary, too large, missing, or no `git`), so the caller falls back to
/// treating the whole file as a conflict.
pub fn merge_text(ours: &Path, ancestor: &Path, theirs: &Path, favor: Favor) -> Option<Merged> {
    for path in [ours, ancestor, theirs] {
        let metadata = fs::symlink_metadata(path).ok()?;
        if !metadata.is_file() || metadata.len() > MAX_MERGE_BYTES || is_binary(path) {
            return None;
        }
    }
    if !git_available() {
        return None;
    }
    let mut command = Command::new("git");
    command.args(["merge-file", "-p", "--diff3"]);
    match favor {
        Favor::Neither => {}
        Favor::Workspace => {
            command.arg("--ours");
        }
        Favor::Project => {
            command.arg("--theirs");
        }
    }
    let output = command
        .args(["-L", "workspace", "-L", "fork", "-L", "project"])
        .arg(ours)
        .arg(ancestor)
        .arg(theirs)
        .stdin(Stdio::null())
        .stderr(Stdio::null())
        .output()
        .ok()?;
    // The exit status is the number of conflicting hunks (capped at 127); anything else,
    // including death by signal, is an error.
    match output.status.code()? {
        0 => Some(Merged::Clean(output.stdout)),
        hunks @ 1..=127 => Some(Merged::Conflicted(output.stdout, hunks as usize)),
        _ => None,
    }
}

/// Whether `path` still holds a conflict hunk written by [`merge_text`].
pub fn has_conflict_markers(path: &Path) -> bool {
    fs::read(path).is_ok_and(|bytes| {
        bytes.split(|byte| *byte == b'\n').any(|line| {
            line == OURS_MARKER.as_bytes() || line.starts_with(THEIRS_MARKER.as_bytes())
        })
    })
}

/// Lockfiles are regenerated by the package manager after a transfer, never merged as text.
pub fn is_lockfile(path: &Path) -> bool {
    path.file_name()
        .and_then(|name| name.to_str())
        .is_some_and(|name| {
            matches!(
                name,
                "package-lock.json"
                    | "pnpm-lock.yaml"
                    | "yarn.lock"
                    | "bun.lock"
                    | "bun.lockb"
                    | "Cargo.lock"
                    | "uv.lock"
                    | "poetry.lock"
            )
        })
}

fn git_available() -> bool {
    static AVAILABLE: OnceLock<bool> = OnceLock::new();
    *AVAILABLE.get_or_init(|| {
        Command::new("git")
            .arg("--version")
            .stdin(Stdio::null())
            .stdout(Stdio::null())
            .stderr(Stdio::null())
            .status()
            .is_ok_and(|status| status.success())
    })
}

/// What became of the paths both sides changed.
#[derive(Debug, Default)]
pub(crate) struct Reconciled {
    /// Journal steps installing the staged merges of `auto_merged` and `marked`.
    pub steps: Vec<MergedStep>,
    /// Combined line by line without overlap.
    pub auto_merged: Vec<PathBuf>,
    /// Staged with conflict markers around overlapping hunks (only when markers are allowed).
    pub marked: Vec<PathBuf>,
    /// Lockfiles where the project's version wins and the install step regenerates them.
    pub project_wins: Vec<PathBuf>,
    /// Text files with overlapping hunks that were not staged (markers not allowed).
    pub overlapping: Vec<PathBuf>,
    /// Everything else: whole-file conflicts, as before line-level merging.
    pub whole_file: Vec<PathBuf>,
}

/// How [`reconcile`] treats overlaps and lockfiles.
#[derive(Debug, Clone, Copy)]
pub(crate) struct Policy {
    pub favor: Favor,
    /// Stage overlapping hunks between conflict markers (pull) instead of refusing (merge).
    pub allow_markers: bool,
    /// The package manager's install step runs after the transfer and can regenerate a
    /// lockfile from the merged manifest.
    pub install_runs: bool,
}

/// Merge every path in `both_changed` line by line: the workspace's version (`view`) against
/// the project's (`workspace.base`) on top of the fork-time version. Results are staged under
/// `staging`, to be installed over `target_root` by the journal.
pub(crate) fn reconcile(
    workspace: &Workspace,
    both_changed: &[PathBuf],
    view: &Path,
    target_root: &Path,
    staging: &Path,
    policy: Policy,
) -> Result<Reconciled> {
    let mut result = Reconciled::default();
    let regenerates_lockfiles = policy.install_runs && detect_package_manager(workspace).is_some();
    for path in both_changed {
        if is_js_lockfile(path) && regenerates_lockfiles {
            result.project_wins.push(path.clone());
            continue;
        }
        let ours = view.join(path);
        let theirs = workspace.base.join(path);
        let merged = ancestor::file(workspace, path)
            .and_then(|ancestor| merge_text(&ours, &ancestor, &theirs, policy.favor));
        let bytes = match merged {
            Some(Merged::Clean(bytes)) => {
                result.auto_merged.push(path.clone());
                bytes
            }
            Some(Merged::Conflicted(bytes, _)) if policy.allow_markers => {
                result.marked.push(path.clone());
                bytes
            }
            Some(Merged::Conflicted(..)) => {
                result.overlapping.push(path.clone());
                continue;
            }
            None => {
                result.whole_file.push(path.clone());
                continue;
            }
        };
        let target = target_root.join(path);
        let Some(expected) = Fingerprint::of(&target) else {
            result.whole_file.push(path.clone());
            continue;
        };
        let expected = Some(expected);
        stage(&staging.join(path), &bytes, &ours)?;
        result.steps.push(MergedStep {
            path: path.clone(),
            expected,
        });
    }
    Ok(result)
}

/// Write a merge result with the workspace file's permissions.
fn stage(staged: &Path, bytes: &[u8], ours: &Path) -> Result {
    if let Some(parent) = staged.parent() {
        fs::create_dir_all(parent).io_context(|| format!("create {}", parent.display()))?;
    }
    fs::write(staged, bytes).io_context(|| format!("stage merge {}", staged.display()))?;
    if let Ok(metadata) = fs::metadata(ours) {
        fs::set_permissions(staged, fs::Permissions::from_mode(metadata.mode() & 0o7777))
            .io_context(|| format!("set permissions on {}", staged.display()))?;
    }
    Ok(())
}

/// Lockfiles the JavaScript install step (`src/sync/install.rs`) regenerates.
fn is_js_lockfile(path: &Path) -> bool {
    is_lockfile(path)
        && path
            .file_name()
            .and_then(|name| name.to_str())
            .is_some_and(|name| {
                matches!(
                    name,
                    "package-lock.json" | "pnpm-lock.yaml" | "yarn.lock" | "bun.lock" | "bun.lockb"
                )
            })
}

#[cfg(test)]
mod tests {
    use super::*;

    fn files(
        ours: &str,
        ancestor: &str,
        theirs: &str,
    ) -> (tempfile::TempDir, [std::path::PathBuf; 3]) {
        let dir = tempfile::tempdir().unwrap();
        let paths = ["ours", "ancestor", "theirs"].map(|name| dir.path().join(name));
        for (path, text) in paths.iter().zip([ours, ancestor, theirs]) {
            fs::write(path, text).unwrap();
        }
        (dir, paths)
    }

    #[test]
    fn edits_far_apart_merge_cleanly() {
        let ancestor = (1..=20).map(|n| format!("line {n}\n")).collect::<String>();
        let ours = ancestor.replace("line 2\n", "line 2 workspace\n");
        let theirs = ancestor.replace("line 18\n", "line 18 project\n");
        let (_dir, [o, a, t]) = files(&ours, &ancestor, &theirs);
        let Some(Merged::Clean(bytes)) = merge_text(&o, &a, &t, Favor::Neither) else {
            panic!("expected a clean merge");
        };
        let text = String::from_utf8(bytes).unwrap();
        assert!(text.contains("line 2 workspace\n") && text.contains("line 18 project\n"));
    }

    #[test]
    fn overlapping_edits_get_labelled_markers() {
        let (dir, [o, a, t]) = files("a\nours\nc\n", "a\nb\nc\n", "a\ntheirs\nc\n");
        let Some(Merged::Conflicted(bytes, 1)) = merge_text(&o, &a, &t, Favor::Neither) else {
            panic!("expected one conflict");
        };
        let merged = dir.path().join("merged");
        fs::write(&merged, &bytes).unwrap();
        assert!(has_conflict_markers(&merged));
        let Some(Merged::Clean(bytes)) = merge_text(&o, &a, &t, Favor::Project) else {
            panic!("--theirs resolves the hunk");
        };
        assert_eq!(bytes, b"a\ntheirs\nc\n");
    }

    #[test]
    fn binary_files_are_not_merged() {
        let (_dir, [o, a, t]) = files("a\0b", "a\0c", "a\0d");
        assert_eq!(merge_text(&o, &a, &t, Favor::Neither), None);
    }
}
